// Builds the studio's built-in mob library from a directory of `.mcvox` captures
// exported by the capture mod. The source directory is passed on the command
// line so the two repositories stay decoupled:
//
//   pnpm build:mobs "D:/path/to/capture/run/entity-capture"
//
// For every entity id it keeps the newest capture, copies it into
// `public/mobs/<id>.mcvox` and writes `src/lib/voxel/builtin-mobs.ts`.
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const sourceDir = process.argv[2];
if (!sourceDir) {
  console.error("用法: node scripts/build-mob-library.mjs <entity-capture 目录>");
  process.exit(1);
}

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const publicDir = join(root, "public", "mobs");
const manifestPath = join(root, "src", "lib", "voxel", "builtin-mobs.ts");

// Vanilla bucket per entity id (path only). Anything unknown defaults to passive.
const WATER = new Set(["cod", "pufferfish", "salmon", "tropical_fish", "dolphin", "squid", "glow_squid"]);
const HOSTILE = new Set([
  "blaze", "bogged", "breeze", "cave_spider", "creeper", "drowned", "elder_guardian", "ender_dragon",
  "enderman", "endermite", "evoker", "ghast", "giant", "guardian", "hoglin", "husk", "illusioner",
  "magma_cube", "phantom", "piglin", "piglin_brute", "pillager", "ravager", "shulker", "silverfish",
  "skeleton", "slime", "spider", "stray", "vex", "vindicator", "warden", "witch", "wither",
  "wither_skeleton", "zoglin", "zombie", "zombie_villager", "zombified_piglin",
]);

function categoryFor(id) {
  const path = id.startsWith("minecraft:") ? id.slice("minecraft:".length) : id;
  if (WATER.has(path)) return "water";
  if (HOSTILE.has(path)) return "hostile";
  return "passive";
}

function readHeader(file) {
  const bytes = readFileSync(file);
  const headerLength = bytes.readUInt32LE(8);
  return JSON.parse(bytes.toString("utf8", 12, 12 + headerLength));
}

function fileBaseFor(id) {
  return id.startsWith("minecraft:") ? id.slice("minecraft:".length) : id.replace(/:/g, "_");
}

// Newest capture per entity id.
const newest = new Map();
for (const name of readdirSync(sourceDir)) {
  if (!name.endsWith(".mcvox")) continue;
  const match = name.match(/^(.+)_(\d{4}-\d{2}-\d{2}T[\d-]+Z)\.mcvox$/);
  if (!match) continue;
  const stamp = match[2];
  let header;
  try {
    header = readHeader(join(sourceDir, name));
  } catch {
    continue;
  }
  if (!header?.entityId) continue;
  const previous = newest.get(header.entityId);
  if (!previous || stamp > previous.stamp) {
    newest.set(header.entityId, { name, stamp, header });
  }
}

mkdirSync(publicDir, { recursive: true });

const mobs = [];
for (const { name, header } of newest.values()) {
  const id = header.entityId;
  const file = `${fileBaseFor(id)}.mcvox`;
  copyFileSync(join(sourceDir, name), join(publicDir, file));
  mobs.push({ id, name: header.entityName || id, category: categoryFor(id), file });
}

mobs.sort((a, b) => a.name.localeCompare(b.name, "zh"));

const lines = mobs
  .map((m) => `  { id: ${JSON.stringify(m.id)}, name: ${JSON.stringify(m.name)}, category: ${JSON.stringify(m.category)}, file: ${JSON.stringify(m.file)} },`)
  .join("\n");

const manifest = `// AUTO-GENERATED by scripts/build-mob-library.mjs — do not edit by hand.
// Rebuild with: pnpm build:mobs "<path to capture/run/entity-capture>"

export type MobCategory = "passive" | "water" | "hostile";

export interface BuiltinMob {
  /** Namespaced entity id, e.g. \`minecraft:zombie\`. */
  id: string;
  /** Localized display name baked in at capture time. */
  name: string;
  category: MobCategory;
  /** File name under \`public/mobs/\`. */
  file: string;
}

export const BUILTIN_MOBS: BuiltinMob[] = [
${lines}
];

const BASE = import.meta.env?.BASE_URL ?? "/";

/** Served URL of a built-in capture. */
export function mobUrl(file: string): string {
  return \`\${BASE}mobs/\${file}\`;
}
`;

writeFileSync(manifestPath, manifest);
console.log(`Copied ${mobs.length} mobs to ${publicDir}`);
console.log(`Wrote ${manifestPath}`);
