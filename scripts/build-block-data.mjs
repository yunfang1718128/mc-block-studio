/**
 * Turn the downloaded textures into a build-time data module.
 *
 *   node scripts/build-block-data.mjs
 *
 * For every block in `scripts/blocks.mjs` it computes the average colour,
 * per-channel variance and mean alpha of its side texture (used for nearest
 * colour matching), records the per-face texture names, and writes the result
 * to `src/lib/blocks/blocks.generated.ts`.
 *
 * Blocks whose side texture is missing from `public/blocks/` are skipped with
 * a warning rather than failing the build.
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { PNG } from "pngjs";
import { blocks, resolveFaces } from "./blocks.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const BLOCKS_DIR = path.join(ROOT, "public", "blocks");
const OUT_FILE = path.join(ROOT, "src", "lib", "blocks", "blocks.generated.ts");

/** @param {string} name */
function texturePath(name) {
  return path.join(BLOCKS_DIR, `${name}.png`);
}

/** Average colour / variance / alpha of a texture, compositing onto grey. */
function analyse(name) {
  const png = PNG.sync.read(readFileSync(texturePath(name)));
  const pixels = png.width * png.height;
  let rSum = 0, gSum = 0, bSum = 0, aSum = 0;
  let rSq = 0, gSq = 0, bSq = 0;

  for (let i = 0; i < png.data.length; i += 4) {
    const a = png.data[i + 3];
    const af = a / 255;
    const r = png.data[i] * af + 128 * (1 - af);
    const g = png.data[i + 1] * af + 128 * (1 - af);
    const b = png.data[i + 2] * af + 128 * (1 - af);
    aSum += a;
    rSum += r; gSum += g; bSum += b;
    rSq += r * r; gSq += g * g; bSq += b * b;
  }

  const rm = rSum / pixels, gm = gSum / pixels, bm = bSum / pixels;
  const variance =
    (rSq / pixels - rm * rm + (gSq / pixels - gm * gm) + (bSq / pixels - bm * bm)) / 3;

  return {
    rgb: [Math.round(rm), Math.round(gm), Math.round(bm)],
    variance: Math.round(variance),
    alpha: Math.round(aSum / pixels),
  };
}

function main() {
  const entries = [];
  const missing = [];
  const fallbacks = [];

  for (const b of blocks) {
    if (!existsSync(texturePath(b.side))) {
      missing.push(b.side);
      continue;
    }
    const faces = resolveFaces(b);
    for (const [dir, name] of Object.entries(faces)) {
      if (!existsSync(texturePath(name))) {
        fallbacks.push(`${b.java}.${dir} → ${name}`);
        faces[dir] = b.side;
      }
    }
    const { rgb, variance, alpha } = analyse(b.side);
    entries.push({
      id: b.java,
      name: b.name,
      category: b.category,
      kind: b.kind ?? "solid",
      rgb,
      variance,
      alpha,
      faces,
    });
  }

  const body = entries
    .map(
      (e) =>
        `  { id: ${JSON.stringify(e.id)}, name: ${JSON.stringify(e.name)}, category: ${JSON.stringify(
          e.category
        )}, kind: ${JSON.stringify(e.kind)}, rgb: [${e.rgb.join(", ")}], variance: ${e.variance}, alpha: ${
          e.alpha
        }, faces: ${JSON.stringify(e.faces)} },`
    )
    .join("\n");

  const out = `// AUTO-GENERATED by scripts/build-block-data.mjs — do not edit by hand.
import type { BlockInfo } from "./types";

export const BLOCKS: BlockInfo[] = [
${body}
];

export const CATEGORIES: string[] = ${JSON.stringify(
    [...new Set(entries.map((e) => e.category))]
  )};
`;

  writeFileSync(OUT_FILE, out);
  console.log(`Wrote ${entries.length} blocks to ${path.relative(ROOT, OUT_FILE)}`);
  if (missing.length) {
    console.warn(`Skipped ${missing.length} block(s) with missing textures: ${missing.join(", ")}`);
  }
  if (fallbacks.length) {
    console.warn(
      `Fell back to the side texture for ${fallbacks.length} missing face(s):\n  ${fallbacks.join("\n  ")}`
    );
  }
}

main();
